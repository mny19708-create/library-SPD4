const khmerDigits = '០១២៣៤៥៦៧៨៩';
const latinDigits = '0123456789';
const englishEntries = Object.entries(translations)
	.filter(([khmer, english]) => khmer !== english)
	.sort(([left], [right]) => right.length - left.length);
const khmerEntries = englishEntries.map(([khmer, english]) => [english, khmer])
	.sort(([left], [right]) => right.length - left.length);

export function translateText(value, locale) {
	if (locale === 'en') {
		let translated = value;
		for (const [khmer, english] of englishEntries) translated = translated.split(khmer).join(english);
		return translated.replace(/[០-៩]/g, digit => latinDigits[khmerDigits.indexOf(digit)]);
	}

	let translated = value;
	for (const [english, khmer] of khmerEntries) translated = translated.split(english).join(khmer);
	return translated;
}

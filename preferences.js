function translatePreferenceText(value, language) {
    const trimmed = value.trim();
    if (!trimmed) return value;

    let translated = trimmed;
    if (language === 'km') {
        translated = preferenceTranslations[trimmed] || trimmed;
        const roomQrTitle = trimmed.match(/^QR Code: (.+)$/);
        const returnedMatch = trimmed.match(/^"(.+)" has been marked as returned\.$/);
        const roomUpdatedMatch = trimmed.match(/^Updated the status of (.+) successfully\.$/);
        const roomUserMatch = trimmed.match(/^User: (.+)$/);
        if (roomQrTitle) translated = `កូដ QR៖ ${roomQrTitle[1]}`;
        if (returnedMatch) translated = `បានកត់ត្រាថា "${returnedMatch[1]}" បានសងរួច។`;
        if (roomUpdatedMatch) translated = `បានកែប្រែស្ថានភាព ${roomUpdatedMatch[1]} ដោយជោគជ័យ។`;
        if (roomUserMatch) translated = `អ្នកប្រើប្រាស់៖ ${roomUserMatch[1]}`;
    } else {
        translated = reversePreferenceTranslations[trimmed] || trimmed;
        const roomQrTitle = trimmed.match(/^កូដ QR៖ (.+)$/);
        const returnedMatch = trimmed.match(/^បានកត់ត្រាថា "(.+)" បានសងរួច។$/);
        const roomUpdatedMatch = trimmed.match(/^បានកែប្រែស្ថានភាព (.+) ដោយជោគជ័យ។$/);
        const roomUserMatch = trimmed.match(/^អ្នកប្រើប្រាស់៖ (.+)$/);
        if (roomQrTitle) translated = `QR Code: ${roomQrTitle[1]}`;
        if (returnedMatch) translated = `"${returnedMatch[1]}" has been marked as returned.`;
        if (roomUpdatedMatch) translated = `Updated the status of ${roomUpdatedMatch[1]} successfully.`;
        if (roomUserMatch) translated = `User: ${roomUserMatch[1]}`;
    }

    return value.replace(trimmed, translated);
}

function applyInterfaceLanguage(language) {
    const selectedLanguage = language === 'km' ? 'km' : 'en';
    document.documentElement.lang = selectedLanguage;
    document.title = translatePreferenceText(document.title, selectedLanguage);

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) {
        textNode.nodeValue = translatePreferenceText(textNode.nodeValue, selectedLanguage);
    }

    document.querySelectorAll('[placeholder]').forEach(element => {
        element.placeholder = translatePreferenceText(element.placeholder, selectedLanguage);
    });
    document.querySelectorAll('[title]').forEach(element => {
        element.title = translatePreferenceText(element.title, selectedLanguage);
    });
}

function applyInterfaceTheme(theme) {
    document.documentElement.classList.toggle('light-mode', theme === 'light');
}

function initializePreferences() {
    const theme = localStorage.getItem('admin-theme') === 'light' ? 'light' : 'dark';
    const language = localStorage.getItem('admin-language') === 'km' ? 'km' : 'en';
    applyInterfaceTheme(theme);
    applyInterfaceLanguage(language);

    const themeSelect = document.getElementById('theme-select');
    if (themeSelect) {
        themeSelect.value = theme;
        themeSelect.addEventListener('change', () => {
            localStorage.setItem('admin-theme', themeSelect.value);
            applyInterfaceTheme(themeSelect.value);
        });
    }

    const languageSelect = document.getElementById('language-select');
    if (languageSelect) {
        languageSelect.value = language;
        languageSelect.addEventListener('change', () => {
            localStorage.setItem('admin-language', languageSelect.value);
            applyInterfaceLanguage(languageSelect.value);
        });
    }

    const observer = new MutationObserver(records => {
        const currentLanguage = localStorage.getItem('admin-language') === 'km' ? 'km' : 'en';
        for (const record of records) {
            if (record.type === 'characterData') {
                const translated = translatePreferenceText(record.target.nodeValue, currentLanguage);
                if (translated !== record.target.nodeValue) record.target.nodeValue = translated;
            } else {
                record.addedNodes.forEach(node => {
                    if (node.nodeType === Node.TEXT_NODE) {
                        const translated = translatePreferenceText(node.nodeValue, currentLanguage);
                        if (translated !== node.nodeValue) node.nodeValue = translated;
                    } else if (node.nodeType === Node.ELEMENT_NODE) {
                        const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
                        let textNode;
                        while ((textNode = walker.nextNode())) {
                            const translated = translatePreferenceText(textNode.nodeValue, currentLanguage);
                            if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
                        }
                        if (node.matches('[placeholder]')) {
                            node.placeholder = translatePreferenceText(node.placeholder, currentLanguage);
                        }
                    }
                });
            }
        }
    });
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
}

initializePreferences();
